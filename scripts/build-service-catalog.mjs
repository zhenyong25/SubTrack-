import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const slug = value => value.toLowerCase().normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const domainPattern = /^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/;
const services = [];
const featured = ['Netflix', 'Spotify', 'YouTube Premium', 'Disney+', 'Amazon Prime', 'ChatGPT', 'Apple Music', 'Google One', 'iCloud+', 'Microsoft 365', 'Claude', 'Canva', 'Notion', 'Dropbox', 'Xbox Game Pass', 'PlayStation Plus', 'Duolingo', 'Strava', 'Astro', 'sooka', 'GrabUnlimited', 'Viu', 'meWATCH', 'Apple One'];
let category = '';
for (const line of readFileSync(new URL('data/subscription-services.txt', root), 'utf8').split(/\r?\n/)) {
  if (!line.trim()) continue;
  if (line.startsWith('# ')) { category = line.slice(2).trim(); continue; }
  const [name, domain, aliases = ''] = line.split('|');
  if (!category || !name || !domainPattern.test(domain)) throw new Error(`Invalid catalog entry: ${line}`);
  services.push({
    id: `${slug(name)}--${slug(domain)}`, name, domain, category,
    aliases: aliases.split(',').filter(Boolean), logo_url: null,
    sort_order: featured.includes(name) ? featured.indexOf(name) : services.length + 100, is_active: true,
  });
}
const ids = services.map(service => service.id);
if (new Set(ids).size !== ids.length) throw new Error('Duplicate service IDs');
if (services.length < 1000) throw new Error('Expected at least 1,000 catalog entries');
const quote = value => `'${value.replace(/'/g, "''")}'`;
const sql = `-- Generated by npm run catalog:build. Edit data/subscription-services.txt instead.
-- Run the entire file in the Supabase SQL editor. Safe to rerun; preserves admin edits.
-- Catalog ordering is editorial, not a measured global popularity ranking.
begin;

create table if not exists public.subscription_services (
  id text primary key,
  name text not null,
  domain text not null check (domain ~ '^[a-z0-9.-]+[.][a-z]{2,}$'),
  category text not null default 'General',
  aliases text[] not null default '{}',
  logo_url text check (logo_url is null or logo_url like 'https://%'),
  sort_order integer not null default 10000,
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);
create index if not exists subscription_services_name_idx on public.subscription_services (lower(name));
create index if not exists subscription_services_order_idx on public.subscription_services (sort_order, id);
alter table public.subscription_services enable row level security;
revoke all on public.subscription_services from anon, authenticated;
grant select on public.subscription_services to anon, authenticated;
grant all on public.subscription_services to service_role;
drop policy if exists "Read subscription service catalog" on public.subscription_services;
create policy "Read subscription service catalog" on public.subscription_services
  for select to anon, authenticated using (true);

-- No FK: a saved subscription must survive catalog retirement and offline additions.
alter table if exists public.subscriptions add column if not exists service_id text;

insert into public.subscription_services (id, name, domain, category, aliases, logo_url, sort_order, is_active)
values
${services.map(s => `(${quote(s.id)}, ${quote(s.name)}, ${quote(s.domain)}, ${quote(s.category)}, ARRAY[${s.aliases.map(quote).join(',')}]::text[], null, ${s.sort_order}, true)`).join(',\n')}
on conflict (id) do nothing;

commit;
`;
const outputs = [
  ['data/subscriptionServices.ts', `// Generated by npm run catalog:build. Do not edit.\nexport default ${JSON.stringify(services)};\n`],
  ['supabase_subscription_services_schema.sql', sql],
];
for (const [path, content] of outputs) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== content) throw new Error(`Catalog output is stale: ${fileURLToPath(url)}`);
  } else writeFileSync(url, content);
}
console.log(`Validated ${services.length} services across ${new Set(services.map(s => s.category)).size} categories.`);

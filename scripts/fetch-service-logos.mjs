// Download actual website icons; does not generate or redraw brand artwork.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const assets = new URL('public/service-logos/', root);
const manifestUrl = new URL('data/service-logo-sources.json', root);
mkdirSync(assets, { recursive: true });
const domains = [...new Set(readFileSync(new URL('data/subscription-services.txt', root), 'utf8')
  .split(/\r?\n/).filter(line => line && !line.startsWith('#')).map(line => line.split('|')[1]))];
const limitArg = process.argv.find(arg => arg.startsWith('--limit='));
const selected = limitArg ? domains.slice(0, Number(limitArg.slice(8))) : domains;
const sources = existsSync(manifestUrl) ? JSON.parse(readFileSync(manifestUrl, 'utf8')) : {};
const refresh = process.argv.includes('--refresh');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const genericHashes = new Set();
const urls = domain => [
  `https://www.google.com/s2/favicons?domain=${encodeURIComponent(domain)}&sz=128`,
  `https://icons.duckduckgo.com/ip3/${encodeURIComponent(domain)}.ico`,
  `https://${domain}/favicon.ico`,
];
const imageType = bytes => {
  if (bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) return 'png';
  if (bytes.length > 22 && bytes.readUInt32LE(0) === 65536 && bytes.readUInt16LE(4) > 0) return 'ico';
  return null;
};

async function fetchImage(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(12000), headers: { 'User-Agent': 'SubTrack-ServiceCatalog/1.0' } });
  const bytes = Buffer.from(await response.arrayBuffer());
  const extension = imageType(bytes);
  if (!response.ok || !extension || bytes.length > 512_000 || genericHashes.has(hash(bytes))) throw new Error(`No usable icon (${response.status})`);
  return { bytes, extension };
}

// Some icon services return a generic globe with HTTP 200. Exclude that artwork.
for (const url of urls('subtrack-no-such-brand-765431.invalid').slice(0, 2)) {
  try {
    const response = await fetch(url, { signal: AbortSignal.timeout(12000) });
    const bytes = Buffer.from(await response.arrayBuffer());
    if (imageType(bytes)) genericHashes.add(hash(bytes));
  } catch { /* Each real brand is still checked independently. */ }
}

let index = 0;
let completed = 0;
let downloaded = 0;
let reused = 0;
const missing = [];
async function worker() {
  while (index < selected.length) {
    const domain = selected[index++];
    if (!/^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/.test(domain)) throw new Error(`Invalid domain: ${domain}`);
    if (!refresh && sources[domain]?.file && existsSync(new URL(`public${sources[domain].file}`, root))) {
      reused++;
    } else {
      let found = false;
      for (const url of urls(domain)) {
        try {
          const { bytes, extension } = await fetchImage(url);
          const file = `${domain}.${extension}`;
          writeFileSync(new URL(file, assets), bytes);
          sources[domain] = { file: `/service-logos/${file}`, source: url, downloadedAt: new Date().toISOString(), sha256: hash(bytes), bytes: bytes.length };
          downloaded++;
          found = true;
          break;
        } catch { /* Try another source before falling back to initials in the app. */ }
      }
      if (!found) missing.push(domain);
    }
    completed++;
    if (completed % 100 === 0) console.log(`${completed}/${selected.length}: ${downloaded} downloaded, ${reused} existing, ${missing.length} unavailable`);
  }
}
await Promise.all(Array.from({ length: 8 }, worker));
const ordered = Object.fromEntries(Object.entries(sources).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(manifestUrl, JSON.stringify(ordered, null, 2) + '\n');
writeFileSync(new URL('data/serviceLogoAssets.ts', root), `// Generated by npm run logos:fetch. Actual website icons served locally.\nconst assets: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(ordered).map(([domain, entry]) => [domain, entry.file])))};\nexport default assets;\n`);
writeFileSync(new URL('data/service-logo-missing.json', root), JSON.stringify(missing, null, 2) + '\n');
console.log(`Finished: ${downloaded} downloaded, ${reused} existing, ${missing.length} unavailable. ${Object.keys(ordered).length} local brand icons in ${fileURLToPath(assets)}`);
if (!Object.keys(ordered).length) throw new Error('No logos downloaded. Check network access.');
